"""
build_icon_atlas.py - packs the UI icons into ONE texture (.claude/commands/art-8.md).

  python tools/build_icon_atlas.py --import <key> <raw.png>   # add / replace one icon
  python tools/build_icon_atlas.py                             # (re)build the atlas

Sources:  art/icons/<key>.png     trimmed to the icon and fitted into 256 x 256 (transparent)
Output:   art/IconAtlas.png       an 8-column grid of 128 px cells, in IconConfig.AtlasOrder
          src/shared/Config/IconAtlas.luau   which key sits in which cell (generated)

Only keys that HAVE a source PNG get a cell entry, so missing icons keep their emoji fallback.
The uploaded atlas id (assetId in IconAtlas.luau) is preserved across rebuilds: rebuild, upload
the new PNG, then paste the new id there. Requires Pillow.
"""

import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.join(ROOT, "art", "icons")
ATLAS_PNG = os.path.join(ROOT, "art", "IconAtlas.png")
ICON_CONFIG = os.path.join(ROOT, "src", "shared", "Config", "IconConfig.luau")
ATLAS_LUAU = os.path.join(ROOT, "src", "shared", "Config", "IconAtlas.luau")

CELL = 128
COLUMNS = 8
SOURCE = 256  # stored source size
MARGIN = 0.06  # empty border inside each cell (fraction of the cell)
LUAU_KEYWORDS = {
    "and", "break", "continue", "do", "else", "elseif", "end", "export", "false", "for", "function",
    "if", "in", "local", "nil", "not", "or", "repeat", "return", "then", "true", "type", "typeof",
    "until", "while",
}


def atlas_order():
    text = open(ICON_CONFIG, encoding="utf-8").read()
    match = re.search(r"IconConfig\.AtlasOrder = \{(.*?)\}", text, re.S)
    if match is None:
        raise SystemExit("IconConfig.AtlasOrder not found")
    # Digits too: keys like "yield_2x" must keep their place (or every later cell shifts).
    return re.findall(r'"([A-Za-z0-9_]+)"', match.group(1))


def fit(image, size, margin):
    """Trim to the alpha bounding box and centre it in a size x size transparent square."""
    image = image.convert("RGBA")
    box = image.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
    if box is not None:
        image = image.crop(box)
    inner = int(round(size * (1 - 2 * margin)))
    scale = min(inner / image.width, inner / image.height)
    resized = image.resize(
        (max(1, round(image.width * scale)), max(1, round(image.height * scale))),
        Image.LANCZOS,
    )
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.paste(resized, ((size - resized.width) // 2, (size - resized.height) // 2), resized)
    return canvas


def import_icon(key, path):
    if key not in atlas_order():
        raise SystemExit(f"{key!r} is not in IconConfig.AtlasOrder")
    os.makedirs(ICONS, exist_ok=True)
    fit(Image.open(path), SOURCE, 0.0).save(os.path.join(ICONS, key + ".png"))
    print("imported", key)


def existing_asset_id():
    if not os.path.exists(ATLAS_LUAU):
        return 0
    match = re.search(r"assetId = (\d+)", open(ATLAS_LUAU, encoding="utf-8").read())
    return int(match.group(1)) if match else 0


def build():
    order = atlas_order()
    rows = (len(order) + COLUMNS - 1) // COLUMNS
    atlas = Image.new("RGBA", (COLUMNS * CELL, rows * CELL), (0, 0, 0, 0))
    cells = []
    for index, key in enumerate(order):
        source = os.path.join(ICONS, key + ".png")
        if not os.path.exists(source):
            continue
        tile = fit(Image.open(source), CELL, MARGIN)
        atlas.paste(tile, ((index % COLUMNS) * CELL, (index // COLUMNS) * CELL), tile)
        cells.append((key, index))
    os.makedirs(os.path.dirname(ATLAS_PNG), exist_ok=True)
    atlas.save(ATLAS_PNG, optimize=True)

    lines = [
        "--!strict",
        "-- GENERATED by tools/build_icon_atlas.py - do not edit by hand, except assetId.",
        "-- ONE texture for every generated icon: art/IconAtlas.png, an 8-column grid of 128 px",
        "-- cells in IconConfig.AtlasOrder. Upload that PNG (Studio Asset Manager), paste its asset",
        "-- id below (0 = not uploaded: every icon keeps its emoji fallback). `cells` only lists keys",
        "-- that have art, so missing icons keep their emoji too.",
        "return {",
        f"\tassetId = {existing_asset_id()},",
        f"\tcell = {CELL},",
        f"\tcolumns = {COLUMNS},",
        f"\twidth = {atlas.width},",
        f"\theight = {atlas.height},",
        "\tcells = {",
    ]
    for key, index in cells:
        # Luau keywords ("function") can't be bare table keys: write them as ["function"].
        field = f'["{key}"]' if key in LUAU_KEYWORDS else key
        lines.append(f"\t\t{field} = {index},")
    lines += ["\t} :: { [string]: number },", "}", ""]
    open(ATLAS_LUAU, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(f"atlas {atlas.width}x{atlas.height}: {len(cells)}/{len(order)} icons -> {os.path.relpath(ATLAS_PNG, ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) == 4 and sys.argv[1] == "--import":
        import_icon(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 1:
        build()
    else:
        raise SystemExit(__doc__)
